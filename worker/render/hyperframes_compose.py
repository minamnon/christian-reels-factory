"""
HyperFrames composition builder for Christian Reels Factory.

Takes the same scene images, voice track, and timing data produced by the
existing pipeline and writes a self-contained HyperFrames project (HTML +
assets) that can be rendered with:

    npx hyperframes render --output output/christian_reel.mp4

This module does NOT replace image generation or voice generation.
It only replaces the final motion / assembly stage when REEL_RENDERER=hyperframes
(or when called from the experimental workflow).
"""

from __future__ import annotations

import json
import math
import os
import shutil
import subprocess
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

# Vertical 9:16 for Reels
WIDTH = 1080
HEIGHT = 1920
FPS = 30

# Camera motion presets (CSS/GSAP equivalents of the old Ken Burns modes)
MOTIONS = ("in", "pan_right", "out", "pan_left", "in_up")


def _esc(s: str) -> str:
    return (
        str(s)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _motion_style(mode: str, duration: float) -> str:
    """Return inline CSS keyframes for a gentle camera move over the image."""
    # We animate a scale/translate on an inner wrapper so the image always
    # covers the 9:16 frame.
    if mode == "in":
        return (
            f"animation: kb-in {duration:.3f}s ease-out both;"
        )
    if mode == "out":
        return (
            f"animation: kb-out {duration:.3f}s ease-in both;"
        )
    if mode == "pan_right":
        return (
            f"animation: kb-pan-right {duration:.3f}s linear both;"
        )
    if mode == "pan_left":
        return (
            f"animation: kb-pan-left {duration:.3f}s linear both;"
        )
    # in_up
    return (
        f"animation: kb-in-up {duration:.3f}s ease-out both;"
    )


def build_composition_html(
    scene_images: Sequence[Path],
    scene_durations: Sequence[float],
    voice_path: Optional[Path],
    subtitle_events: Sequence[Tuple[Path, float, float]],
    total_duration: float,
    topic: str = "",
) -> str:
    """
    Build a complete HyperFrames index.html string.

    scene_images: list of PNG/JPG paths (already generated by image_generation)
    scene_durations: seconds per scene
    voice_path: optional full voice-over audio
    subtitle_events: list of (png_path, start, end) for timed subtitle overlays
    total_duration: total video length in seconds
    """
    assert len(scene_images) == len(scene_durations)

    # CSS for Ken-Burns style moves + subtitle styling.
    # NOTE: all visible text is pre-rendered PNG (Pillow + RAQM), so the page
    # declares no font-family; HyperFrames lint rejects font families without
    # @font-face and would fall back to a generic font (square boxes).
    css = f"""
    * {{ box-sizing: border-box; margin: 0; padding: 0; }}
    html, body {{
      width: {WIDTH}px;
      height: {HEIGHT}px;
      overflow: hidden;
      background: #000;
    }}
    #root {{
      position: relative;
      width: {WIDTH}px;
      height: {HEIGHT}px;
      background: #000;
      overflow: hidden;
    }}
    .clip {{
      position: absolute;
      inset: 0;
      width: 100%;
      height: 100%;
    }}
    .scene-img {{
      position: absolute;
      width: 120%;
      height: 120%;
      left: -10%;
      top: -10%;
      object-fit: cover;
      will-change: transform;
    }}
    @keyframes kb-in {{
      from {{ transform: scale(1); }}
      to   {{ transform: scale(1.12); }}
    }}
    @keyframes kb-out {{
      from {{ transform: scale(1.12); }}
      to   {{ transform: scale(1); }}
    }}
    @keyframes kb-pan-right {{
      from {{ transform: scale(1.08) translateX(4%); }}
      to   {{ transform: scale(1.08) translateX(-4%); }}
    }}
    @keyframes kb-pan-left {{
      from {{ transform: scale(1.08) translateX(-4%); }}
      to   {{ transform: scale(1.08) translateX(4%); }}
    }}
    @keyframes kb-in-up {{
      from {{ transform: scale(1) translateY(0); }}
      to   {{ transform: scale(1.12) translateY(-4%); }}
    }}
    @keyframes fade-in {{
      from {{ opacity: 0; }}
      to   {{ opacity: 1; }}
    }}
    @keyframes fade-out {{
      from {{ opacity: 1; }}
      to   {{ opacity: 0; }}
    }}
    """

    clips_html: List[str] = []
    gsap_tweens: List[str] = []
    t = 0.0
    for i, (img, dur) in enumerate(zip(scene_images, scene_durations)):
        mode = MOTIONS[i % len(MOTIONS)]
        rel = f"assets/scene_{i:02d}{Path(img).suffix.lower()}"
        # Flat timeline element (HyperFrames lint: no nested content inside a
        # timed clip). Camera motion is driven by the GSAP timeline below.
        clips_html.append(
            f'''  <img class="clip scene-img" id="img-{i}" src="{rel}" alt=""
       data-start="{t:.3f}" data-duration="{dur:.3f}" data-track-index="0" />'''
        )
        # Build GSAP tween for this scene's camera move (absolute film time)
        if mode == "in":
            gsap_tweens.append(
                f'tl.fromTo("#img-{i}", {{scale:1,xPercent:0,yPercent:0}}, '
                f'{{scale:1.12,xPercent:0,yPercent:0,duration:{dur:.3f},ease:"none"}}, {t:.3f});'
            )
        elif mode == "out":
            gsap_tweens.append(
                f'tl.fromTo("#img-{i}", {{scale:1.12,xPercent:0,yPercent:0}}, '
                f'{{scale:1.0,xPercent:0,yPercent:0,duration:{dur:.3f},ease:"none"}}, {t:.3f});'
            )
        elif mode == "pan_right":
            gsap_tweens.append(
                f'tl.fromTo("#img-{i}", {{scale:1.08,xPercent:4,yPercent:0}}, '
                f'{{scale:1.08,xPercent:-4,yPercent:0,duration:{dur:.3f},ease:"none"}}, {t:.3f});'
            )
        elif mode == "pan_left":
            gsap_tweens.append(
                f'tl.fromTo("#img-{i}", {{scale:1.08,xPercent:-4,yPercent:0}}, '
                f'{{scale:1.08,xPercent:4,yPercent:0,duration:{dur:.3f},ease:"none"}}, {t:.3f});'
            )
        else:  # in_up
            gsap_tweens.append(
                f'tl.fromTo("#img-{i}", {{scale:1,xPercent:0,yPercent:0}}, '
                f'{{scale:1.12,xPercent:0,yPercent:-4,duration:{dur:.3f},ease:"none"}}, {t:.3f});'
            )
        t += dur

    # Subtitle overlays (PNG from existing Arabic-capable pipeline — already RTL)
    for j, (png, start, end) in enumerate(subtitle_events):
        dur = max(0.05, end - start)
        rel = f"assets/sub_{j:02d}.png"
        clips_html.append(
            f'''  <img class="clip" id="sub-{j}" src="{rel}" alt=""
       data-start="{start:.3f}" data-duration="{dur:.3f}" data-track-index="2"
       style="object-fit: contain; object-position: center bottom;" />'''
        )

    audio_html = ""
    if voice_path and Path(voice_path).exists():
        # data-duration matches composition so audio does not loop past the film
        audio_html = f'''
  <audio id="voice" data-start="0" data-duration="{total_duration:.3f}"
         data-track-index="1" data-volume="1"
         src="assets/voice{Path(voice_path).suffix.lower()}"></audio>'''

    gsap_block = "\n    ".join(gsap_tweens)

    html = f"""<!DOCTYPE html>
<html lang="ar">
<head>
  <meta charset="utf-8" />
  <title>{_esc(topic or "Christian Reel")}</title>
  <style>{css}</style>
  <script src="https://cdn.jsdelivr.net/npm/gsap@3.12.5/dist/gsap.min.js"></script>
</head>
<body>
<div id="root"
     data-composition-id="reel"
     data-start="0"
     data-width="{WIDTH}"
     data-height="{HEIGHT}"
     data-duration="{total_duration:.3f}">
{chr(10).join(clips_html)}
{audio_html}
</div>
<script>
  (function () {{
    var tl = gsap.timeline({{ paused: true }});
    {gsap_block}
    window.__timelines = window.__timelines || {{}};
    window.__timelines.reel = tl;
  }})();
</script>
</body>
</html>
"""
    return html


def write_hyperframes_project(
    work_dir: Path,
    output_dir: Path,
    scene_images: Sequence[Path],
    scene_durations: Sequence[float],
    voice_path: Optional[Path],
    subtitle_events: Sequence[Tuple[Path, float, float]],
    total_duration: float,
    topic: str = "",
) -> Path:
    """
    Create a HyperFrames project folder under work_dir/hf_project
    containing index.html and an assets/ folder with copied media.
    Returns the project directory path.
    """
    project = work_dir / "hf_project"
    assets = project / "assets"
    if project.exists():
        shutil.rmtree(project)
    assets.mkdir(parents=True)

    # Copy scene images
    for i, img in enumerate(scene_images):
        ext = Path(img).suffix.lower() or ".png"
        dest = assets / f"scene_{i:02d}{ext}"
        shutil.copy2(img, dest)

    # Copy voice
    if voice_path and Path(voice_path).exists():
        ext = Path(voice_path).suffix.lower() or ".wav"
        shutil.copy2(voice_path, assets / f"voice{ext}")

    # Copy subtitle PNGs
    for j, (png, _, _) in enumerate(subtitle_events):
        if Path(png).exists():
            shutil.copy2(png, assets / f"sub_{j:02d}.png")

    html = build_composition_html(
        scene_images,
        scene_durations,
        voice_path,
        subtitle_events,
        total_duration,
        topic=topic,
    )
    (project / "index.html").write_text(html, encoding="utf-8")

    # Minimal package marker so hyperframes CLI treats this as a project
    (project / "package.json").write_text(
        json.dumps({"name": "christian-reel-hf", "private": True}, indent=2),
        encoding="utf-8",
    )

    print(f"HyperFrames project written to {project}")
    return project


def _run_hf(cmd: list, cwd: Path, timeout: int = 120) -> subprocess.CompletedProcess:
    print("Running:", " ".join(cmd), "| cwd=", cwd)
    return subprocess.run(
        cmd,
        cwd=str(cwd),
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def render_with_hyperframes(
    project_dir: Path,
    output_mp4: Path,
    timeout_seconds: int = 600,
) -> Path:
    """
    Run the HyperFrames CLI to produce the final MP4.

    Must be invoked with cwd = the project folder that contains index.html.
    Compatible with current CLI:
        npx hyperframes render --output <path>
    """
    project_dir = Path(project_dir).resolve()
    output_mp4 = Path(output_mp4).resolve()
    output_mp4.parent.mkdir(parents=True, exist_ok=True)

    index = project_dir / "index.html"
    if not index.exists():
        raise RuntimeError(f"No index.html in HyperFrames project: {project_dir}")

    # Environment diagnostics (non-fatal)
    for probe in (
        ["npx", "--yes", "hyperframes@latest", "doctor"],
        ["npx", "--yes", "hyperframes@latest", "lint"],
    ):
        try:
            r = _run_hf(probe, project_dir, timeout=90)
            out = (r.stdout or "") + (r.stderr or "")
            print(out[-1500:] if out else f"(no output, code={r.returncode})")
        except Exception as exc:
            print(f"Probe {' '.join(probe)} skipped:", type(exc).__name__, str(exc)[:120])

    # Official local render: run FROM the project directory
    cmd = [
        "npx", "--yes", "hyperframes@latest",
        "render",
        "--output", str(output_mp4),
    ]
    result = _run_hf(cmd, project_dir, timeout=timeout_seconds)
    stdout = result.stdout or ""
    stderr = result.stderr or ""
    if stdout:
        print(stdout[-2500:])
    if result.returncode != 0:
        if stderr:
            print(stderr[-2500:])
        raise RuntimeError(
            f"HyperFrames render failed with code {result.returncode}"
        )

    if not output_mp4.exists() or output_mp4.stat().st_size == 0:
        # Some CLI versions write under renders/ relative to project
        fallback = project_dir / "renders"
        candidates = list(fallback.glob("*.mp4")) if fallback.exists() else []
        if candidates:
            shutil.copy2(candidates[0], output_mp4)
            print(f"Copied fallback render {candidates[0]} -> {output_mp4}")
        else:
            raise RuntimeError("HyperFrames did not produce a valid MP4")

    print(f"HyperFrames MP4 ready: {output_mp4} "
          f"({output_mp4.stat().st_size} bytes)")
    return output_mp4
